// server/http/static.js — the static file server (routes.js hands it every GET / HEAD that is not an API route):
// (i18n-ignore-file: the error pages are bilingual by design, 中文 · English — docs/I18N.md)
//
//     /        → public/      (index.html for directories)
//     /data/   → data/        (generated game data)
//     /shared/ → shared/      (ESM shared with the browser)
//     /sim/    → server/sim/  (the battle simulation, read-only, `.js` only — client-side
//                              combat, DESIGN §14; the Node-only loader nodeData.js is not served)
//     /data.js → a generated browser stand-in of server/data.js (the sim's content modules
//                import `../../../data.js`; in the browser it serves the data injected with
//                /sim/simdata.js setSimData). No other server file is ever served.
//     /media/bgm/act1 → public/assets/audio/bgm/act1.mp3 — the same audio files, addressed
//                **without** an extension so download managers (IDM / 迅雷 …) stop popping a
//                "下载文件信息" dialog for every BGM track (media.js, shared/media.js, public/js/media.js)
//     /packs/index.json → the content packs of this server (server/packs.js: the language packs of
//                public/i18n/ and the pack folders of packs/, re-read when they change; never cached)
//     /packs/<id>/<file> → a file of a pack folder — only one its manifest names (server/packs.js servable)
//
// Traversal & dotfile protection, a directory without its trailing slash → 301, 404 page; an absent
// data/local-assets.json is answered with an empty manifest. Files go out through files.js serveFile.
//
// An install whose art lives on a mirror instead of on disk (no public/fonts/) answers a missing /fonts/… request
// with a 302 to the URL the pinned manifest names for it (asset-cdn.js) instead of a 404, so the stylesheet
// public/index.html links still loads and the game keeps its real fonts instead of the system fallbacks.

import fsp from 'node:fs/promises';
import path from 'node:path';
import { MEDIA_PREFIX } from '../../shared/media.js';
import { ROOT, noopLog } from './config.js';
import { sendError, sendJson } from './common.js';
import { MIME, GzipCache, isNotModified, serveFile, loadWarmFile } from './files.js';
import { createAssetCdn } from './asset-cdn.js';
import { serveMedia } from './media.js';
import { createPackRegistry } from '../packs.js';
import { PACKS_URL, PACK_INDEX_FILE } from '../../shared/packs.js';
import { ANNOUNCEMENTS_PATH } from '../../packages/announcements/announcements.js';

/** Browser stand-in of server/data.js, served at /data.js (see the header). Served byte for byte: its first line names the entry, server/index.js. */
export const DATA_SHIM_JS = `// Generated by server/index.js — browser stand-in for server/data.js (DESIGN §14 client-side combat).
// The simulation's content modules (/sim/content/support/index.js) import getData() from here; it returns the game data
// the page injected with /sim/simdata.js setSimData(data).
import { getSimData } from './sim/simdata.js';
export function getData() { return getSimData() || {}; }
export function resetData() {}
`;
/** Files under server/sim that are never served (Node-only). */
const SIM_PRIVATE = new Set(['nodedata.js']); // lower-case (compared case-insensitively)

// ---------------------------------------------------------------------------------------------------
// Static file handler
// ---------------------------------------------------------------------------------------------------

/** Optional per-machine art manifest (tools/local-extract) and the empty stand-in served when it is absent. */
const LOCAL_ART_MANIFEST = 'local-assets.json';
const EMPTY_LOCAL_ART = Buffer.from(JSON.stringify({ version: 1, source: 'none', count: 0, groups: {} }));

/**
 * Create the static request handler.
 *   packs?: ReturnType<typeof createPackRegistry>, log?: object, warm?: string[],
 *   manifestAlias?: { from: string, to: string, file: string } | null,
 *   assetCdn?: ReturnType<typeof createAssetCdn>,
 *   assetJump?: ((pathname: string, query: string, method: string) => { status: number, headers: Record<string, string> } | null) | null }} dirs
 *   packs: the server's pack registry (default: one over publicDir, dataDir and packsDir — ROOT/packs)
 *   assetJump: missing /assets|fonts files are 302ed to the asset source (server/http/asset-jump.js) — local files still win
 *   assetCdn: the /fonts/ mirror fallback (default: one over dataDir/assets.json); the SECOND chance, after assetJump
 *   announcements: the external notice board (default: none — data/announcements.json on disk is served)
 *   warm: absolute paths read once at boot and then served from memory (server/http/files.js loadWarmFile);
 *         for files the container FS re-reads slowly. The promise is exposed as `handler.warmReady`.
 *   manifestAlias: some edges are slow for one specific URL (measured 2026-10-11: the ModelScope studio served
 *         /data/assets.json at ~140-270 KB/s while every other /data/*.json was fast, and the web client gives up
 *         on the art manifest after 8 s). `from` is answered with a 302 to `to`, and `to` serves `file` from the
 *         warm copy — the client is unchanged, only the URL spelling changes.
 * @returns {(req: import('node:http').IncomingMessage, res: import('node:http').ServerResponse, rawPath: string, query: string) => Promise<void>}
 */
export function createStaticHandler({ publicDir, dataDir, sharedDir, simDir = path.join(ROOT, 'server', 'sim'), packsDir = path.join(ROOT, 'packs'), packs = null, log = noopLog, assetJump = null, warm = [], manifestAlias = null, assetCdn = null, announcements = null }) {
  const registry = packs || createPackRegistry({ publicDir, dataDir, packsDir }, { log: /** @type {any} */ (log) });
  const cdn = assetCdn || createAssetCdn({ manifestPath: path.join(path.resolve(dataDir), 'assets.json'), log });
  // Read the warm list once, off the request path: the bytes (and the gzip) stay in memory for this process' life.
  /** @type {Map<string, { raw: Buffer, gz: Buffer | null, stat: import('node:fs').Stats }>} */
  const warmCache = new Map();
  const warmReady = Promise.all(warm.map(async (p) => {
    const abs = path.resolve(p);
    try {
      const entry = await loadWarmFile(abs);
      warmCache.set(abs, entry);
      log.info?.(`[http] warm: ${abs} (${entry.raw.length} bytes${entry.gz ? `, gzip ${entry.gz.length}` : ''})`);
    } catch (e) {
      log.warn?.(`[http] warm: cannot preload ${abs}: ${e?.message || e}`);
    }
  }));
  const alias = manifestAlias && typeof manifestAlias.from === 'string' && typeof manifestAlias.to === 'string' && typeof manifestAlias.file === 'string'
    ? { from: manifestAlias.from, to: manifestAlias.to, file: path.resolve(manifestAlias.file) }
    : null;
  const mounts = [
    { prefix: '/data/', name: 'data', dir: path.resolve(dataDir) },
    { prefix: '/shared/', name: 'shared', dir: path.resolve(sharedDir) },
    // the simulation: ES modules only (no directory listings, no other file types, no Node-only loader)
    { prefix: '/sim/', name: 'sim', dir: path.resolve(simDir), only: new Set(['.js']), deny: SIM_PRIVATE },
    { prefix: '/', name: 'public', dir: path.resolve(publicDir) },
  ];
  const shimBody = Buffer.from(DATA_SHIM_JS);
  const shimTag = `"shim-${shimBody.length.toString(16)}"`;
  const gzipCache = new GzipCache();

  async function serveStatic(req, res, rawPath, query) {
    let decoded;
    try { decoded = decodeURIComponent(rawPath); } catch { sendError(req, res, 400, '请求地址无效 · Bad request'); return; }
    if (!decoded.startsWith('/') || decoded.includes('\0') || decoded.includes('\\')) {
      sendError(req, res, 400, '请求地址无效 · Bad request');
      return;
    }
    // The manifest alias (see the option's doc): 302 the canonical URL to the fresh one; serve the fresh one
    // from the warm copy — same bytes, same ETag/range/gzip semantics as the file on disk.
    if (alias && decoded === alias.from) {
      res.writeHead(302, { Location: alias.to, 'Cache-Control': 'no-cache', 'Content-Length': 0 });
      res.end();
      return;
    }
    if (alias && decoded === alias.to) {
      const entry = warmCache.get(alias.file);
      const stat = entry ? entry.stat : await fsp.stat(alias.file).catch(() => null);
      if (!stat || !stat.isFile()) { sendError(req, res, 404, '页面不存在 · Not found'); return; }
      await serveFile(req, res, alias.file, stat, 'data', [path.basename(alias.file)], query, gzipCache, log, entry || null);
      return;
    }
    if (decoded === '/data.js') {
      const headers = { 'Content-Type': MIME['.js'], 'Cache-Control': 'no-cache', ETag: shimTag, 'Content-Length': shimBody.length };
      if (isNotModified(req, shimTag, new Date(0))) { delete headers['Content-Length']; res.writeHead(304, headers); res.end(); return; }
      res.writeHead(200, headers);
      res.end(req.method === 'HEAD' ? undefined : shimBody);
      return;
    }
    // Content packs (server/packs.js): the live index, and only the files a pack's manifest names
    if (decoded.startsWith(PACKS_URL)) {
      const parts = decoded.slice(PACKS_URL.length).split('/');
      if (parts.length === 1 && parts[0] === PACK_INDEX_FILE) { sendJson(req, res, 200, registry.index()); return; }
      const abs = parts.length >= 2 && !parts.some((s) => s === '' || s === '.' || s === '..') ? registry.servable(parts[0], parts.slice(1).join('/')) : null;
      const st = abs ? await fsp.stat(abs).catch(() => null) : null;
      if (!st || !st.isFile()) { sendError(req, res, 404, '页面不存在 · Not found', decoded.length <= 200 ? decoded : ''); return; }
      await serveFile(req, res, abs, st, 'packs', parts, query, gzipCache, log);
      return;
    }
    // Extension-less audio (download-manager avoidance): /media/bgm/act1 → /assets/audio/bgm/act1.mp3
    if (decoded.startsWith(MEDIA_PREFIX)) {
      await serveMedia(req, res, decoded.slice(MEDIA_PREFIX.length), query, publicDir, gzipCache, log);
      return;
    }
    // Editorial notices may come from outside this install (server/http/announcements.js): with a source that
    // holds a good body, answer the path from it and never touch the disk. With no source — or one that has
    // never answered — the request falls through to the on-disk file exactly as it always did.
    if (announcements && decoded === ANNOUNCEMENTS_PATH) {
      const body = announcements.body();
      if (body !== null && announcements.fresh()) {
        const payload = Buffer.from(body, 'utf8');
        const tag = `"ann-${payload.length.toString(16)}"`;
        const headers = { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-cache', ETag: tag, 'Content-Length': payload.length };
        if (isNotModified(req, tag, new Date())) { res.writeHead(304, headers); res.end(); return; }
        res.writeHead(200, headers);
        res.end(req.method === 'HEAD' ? undefined : payload);
        return;
      }
    }
    // Bare mount paths (e.g. "/data") → treat as the mount directory.
    const mount = mounts.find((m) => decoded.startsWith(m.prefix) || decoded === m.prefix.slice(0, -1)) || mounts[mounts.length - 1];
    const rest = decoded.length > mount.prefix.length ? decoded.slice(mount.prefix.length) : '';
    const segments = rest.split('/').filter((s) => s.length > 0);
    if (segments.some((s) => s === '..' || s === '.')) { sendError(req, res, 403, '禁止访问 · Forbidden'); return; }
    if (segments.some((s) => s.startsWith('.'))) { sendError(req, res, 404, '页面不存在 · Not found'); return; }
    if (mount.only && (!segments.length || !mount.only.has(path.extname(segments[segments.length - 1]).toLowerCase())
      // (case-insensitive: the host may be Windows / macOS, where NODEDATA.JS opens nodeData.js)
      || (mount.deny && mount.deny.has(segments[segments.length - 1].toLowerCase())))) {
      sendError(req, res, 404, '页面不存在 · Not found');
      return;
    }
    let absPath = path.join(mount.dir, ...segments);
    if (absPath !== mount.dir && !absPath.startsWith(mount.dir + path.sep)) { sendError(req, res, 403, '禁止访问 · Forbidden'); return; }

    let stat;
    let viaDirectory = false;
    try {
      stat = await fsp.stat(absPath);
      if (stat.isDirectory()) {
        if (!decoded.endsWith('/')) {
          // Built from normalized segments (never from the raw path) so "//host" can't become an open redirect.
          const loc = (mount.prefix + segments.map(encodeURIComponent).join('/') + '/').replace(/\/{2,}/g, '/');
          res.writeHead(301, { Location: loc + (query ? `?${query}` : ''), 'Cache-Control': 'no-cache', 'Content-Length': 0 });
          res.end();
          return;
        }
        absPath = path.join(absPath, 'index.html');
        segments.push('index.html');
        viaDirectory = true;
        stat = await fsp.stat(absPath);
      }
      // Not a regular file, or a file addressed like a directory ("/app.js/") → 404.
      if (!stat.isFile() || (decoded.endsWith('/') && !viaDirectory)) {
        throw Object.assign(new Error('not a file'), { code: 'ENOENT' });
      }
      if (mount.deny) {
        // the on-disk name decides (case-insensitive file systems, Windows 8.3 short names like NODEDA~1.JS)
        const real = await fsp.realpath(absPath);
        if (mount.deny.has(path.basename(real).toLowerCase())) throw Object.assign(new Error('private'), { code: 'ENOENT' });
      }
    } catch (e) {
      if (e && e.code === 'ENOENT' && mount.name === 'data' && segments.length === 1 && segments[0] === LOCAL_ART_MANIFEST) {
        // Optional local-client art (DESIGN §13): an install without it gets an empty manifest instead of a 404,
        // so browsers don't log an error on every page load. Clients treat empty groups as "no local art".
        res.writeHead(200, { 'Content-Type': MIME['.json'], 'Cache-Control': 'no-cache', 'Content-Length': EMPTY_LOCAL_ART.length });
        res.end(req.method === 'HEAD' ? undefined : EMPTY_LOCAL_ART);
      } else if (e && (e.code === 'ENOENT' || e.code === 'ENOTDIR' || e.code === 'EISDIR' || e.code === 'ENAMETOOLONG')) {
        // A missing asset (this image carries no art) → 302 to the asset source. Local files never get here:
        // the jump only answers paths whose file is absent (server/http/asset-jump.js, same rules as the edge sidecar).
        //
        // ORDER MATTERS ON THIS BRANCH. assetJump is the deployment's own mechanism: it reads the SAME source table the
        // edge sidecar reads (deploy/stardust/ms-edge/sources.json) and it is what makes the relativized
        // data/assets.json work — the browser asks this container for /assets/… and gets sent to a source, instead of
        // the manifest carrying an absolute CDN URL that bypasses the edge entirely. So it answers first, and the
        // manifest-driven /fonts fallback (asset-cdn.js, kept for installs that wire no jump) is the second chance.
        const jumped = assetJump ? assetJump(decoded, query, req.method, assetJump.config ? assetJump.config() : null) : null;
        if (jumped) { res.writeHead(jumped.status, jumped.headers); res.end(); return; }
        // No public/fonts/ in this image (the art lives on the mirror): point the browser at the URL the pinned
        // manifest names instead of 404-ing the stylesheet on every load. Cached as long as files.js caches the
        // font files themselves, so the redirect does not turn into per-load traffic for the app server.
        const cdnUrl = await cdn.fontUrl(decoded, query);
        if (cdnUrl) {
          res.writeHead(302, { Location: cdnUrl, 'Cache-Control': 'public, max-age=86400', 'Content-Length': 0 });
          res.end();
        } else {
          sendError(req, res, 404, '页面不存在 · Not found', decoded.length <= 200 ? decoded : '');
        }
      } else if (e && (e.code === 'EACCES' || e.code === 'EPERM')) {
        sendError(req, res, 403, '禁止访问 · Forbidden');
      } else {
        log.error('[http] stat failed', e);
        sendError(req, res, 500, '服务器内部错误 · Internal error');
      }
      return;
    }
    // Warm files are served from the boot-time copy (sizes must agree: a changed file falls back to disk).
    const cached = warmCache.get(absPath);
    const useCached = cached && cached.raw.length === stat.size ? cached : null;
    await serveFile(req, res, absPath, useCached ? useCached.stat : stat, mount.name, segments, query, gzipCache, log, useCached);
  };

  // Boot diagnostics and tests can await the preload; requests are served from disk until it lands.
  serveStatic.warmReady = warmReady;
  return serveStatic;
}
